// Package scaffold writes a minimal, working starter DEPLOYMENT from nothing but a
// subscription URL — the "one button" onboarding.
//
// It writes the v2 shape, which is a directory: configuration.yaml plus one file per
// rule. That is not a formality. v1 could say `category: streaming` and inherit the
// escalation chain; v2 has no behaviour profiles, so a rule states its chain step by
// step. The starter therefore writes the chain out, which is also the point — a
// first-run file the operator can read is worth more than one that hides its ladder
// behind a name they then have to look up.
package scaffold

import (
	"bytes"
	_ "embed"
	"fmt"
	"strings"
)

//go:embed recommended.yaml
var recommendedRules []byte

// Deployment is what -init writes to disk: the document, and one file per rule.
type Deployment struct {
	// Document is configuration.yaml.
	Document []byte
	// Rules maps file name to the rule's text, e.g. "youtube.yaml".
	Rules map[string][]byte
}

// desyncInstance is the instance every starter rule's desync rung names. It is
// materialised into the document so the rules reference something that exists —
// a rule naming an undeclared instance is refused at load, and a first-run file
// that does not load is the worst possible first impression.
const desyncInstance = "nfqws1-main"

// chain is the ladder every starter rule gets: desync first (direct egress, low
// latency), the latency-ranked VPN pool as the fallback, and the emergency pool as
// the last resort. It is written out rather than inherited so the operator can see
// what the tool will try, in order, and change one rung without reading a manual.
const chain = `chain:
  - {tier: preferred, desync: {instance: ` + desyncInstance + `, strategy: auto}}
  - {tier: fallback, vpn: {pool: vpn_url_test}}
  - {tier: emergency, vpn: {pool: emergency_pool}}
`

func document(subs []string) []byte {
	var b strings.Builder
	b.WriteString("# Lotsman — main configuration.\n")
	b.WriteString("# One file per rule lives in rules/ beside this. Generated by `lotsman -init`.\n\n")
	b.WriteString("version: 2\n")
	b.WriteString("target_version: \"1.14.1\"\n\n")
	b.WriteString("proxy:\n  engine: sing-box\n  mode: tun\n\n")
	b.WriteString("desync:\n  instances:\n")
	fmt.Fprintf(&b, "    %s:\n      engine: nfqws1\n      enabled: true\n", desyncInstance)
	// The capture set is NOT optional: an instance with no ports installs an nft rule
	// that matches nothing, so the desync is silently absent while every status read
	// reports healthy. 80 and 443 carry the traffic the ladder is meant to rescue; the
	// UDP half is there for QUIC, which is what a lot of clients try first.
	b.WriteString("      capture:\n        tcp: [80, 443]\n        udp: [443, 50000-50100]\n\n")
	if len(subs) > 0 {
		b.WriteString("subscriptions:\n")
		for i, u := range subs {
			// Tag the first subscription `normal` and any others too; a subscription whose
			// nodes should only be a last resort can be retagged `emergency` by hand.
			fmt.Fprintf(&b, "  - { name: sub%d, url: %q, format: auto, tags: [normal], enabled: true }\n", i+1, u)
		}
		b.WriteString("\n")
	}
	b.WriteString("# The three standard pools (vpn_url_test, vpn_url_test_udp, emergency_pool)\n")
	b.WriteString("# are built in. Declare a `pools:` entry only to override them — for example to\n")
	b.WriteString("# keep volume traffic off a saturated exit with `countries_exclude`.\n")
	b.WriteString("pools: {}\n")
	return []byte(b.String())
}

// Recommended returns the curated default deployment shipped with Lotsman — the
// common RU-blocked set on a working ladder, and no creds. If subURLs are given they
// go into the document's subscriptions block; otherwise the deployment ships without
// one and the user adds a subscription later (e.g. in the app).
func Recommended(subURLs []string) Deployment {
	return Deployment{
		Document: document(subURLs),
		Rules:    splitRules(recommendedRules),
	}
}

// starterRule is one rule of the minimal starter: a well-known service with concrete
// domains and a probe, so it works out of the box.
type starterRule struct {
	id, probe string
	domains   []string
	volume    string
}

// starterRules are a sane first set: the services people in Russia most often need
// unblocked. Kept short on purpose — the operator adds their own from here.
var starterRules = []starterRule{
	{"youtube", "https://www.youtube.com/generate_204",
		[]string{"youtube.com", "googlevideo.com", "ytimg.com", "ggpht.com"},
		"https://www.youtube.com/"},
	{"discord", "https://discord.com/api/v9/gateway",
		[]string{"discord.com", "discord.gg", "discordapp.com", "discordapp.net", "discord.media"}, ""},
	{"instagram", "https://www.instagram.com/favicon.ico",
		[]string{"instagram.com", "cdninstagram.com", "fbcdn.net"}, ""},
}

func (r starterRule) file() []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "# %s\n", r.id)
	fmt.Fprintf(&b, "id: %s\n", r.id)
	fmt.Fprintf(&b, "name: %s\n", r.id)
	fmt.Fprintf(&b, "enabled: true\n\n")
	b.WriteString("match:\n")
	fmt.Fprintf(&b, "  domains: [%s]\n\n", strings.Join(r.domains, ", "))
	b.WriteString("probe:\n  type: http\n")
	fmt.Fprintf(&b, "  target: %s\n\n", r.probe)
	if r.volume != "" {
		// volume_target answers "does the path CARRY", which the probe cannot: probes
		// are deliberately tiny, and TSPU lets a flow establish and then freezes it a
		// few tens of KB in. Only rules with one are re-measured for throughput.
		b.WriteString("volume:\n")
		fmt.Fprintf(&b, "  targets: [%s]\n\n", r.volume)
	}
	b.WriteString(chain)
	return b.Bytes()
}

// Starter returns the minimal starter deployment. subURLs are the subscription
// endpoints to pull nodes from; at least one is required by the caller.
func Starter(subURLs []string) Deployment {
	rules := map[string][]byte{}
	for _, r := range starterRules {
		rules[r.id+".yaml"] = r.file()
	}
	return Deployment{Document: document(subURLs), Rules: rules}
}

// splitRules turns the embedded multi-document file into one rule per file. A `---`
// boundary is the separator because it is what the YAML parser already treats as one,
// so the embedded asset is itself valid YAML rather than a format only this package
// understands.
func splitRules(data []byte) map[string][]byte {
	out := map[string][]byte{}
	for _, chunk := range strings.Split(string(data), "\n---") {
		body := strings.TrimSpace(chunk)
		if body == "" {
			continue
		}
		// The id is the first `id:` line; the file name is derived from it so the two
		// cannot drift — a document is readable by listing the directory.
		id := ""
		for _, line := range strings.Split(body, "\n") {
			line = strings.TrimSpace(line)
			if strings.HasPrefix(line, "id:") {
				id = strings.TrimSpace(strings.TrimPrefix(line, "id:"))
				break
			}
		}
		if id == "" {
			continue
		}
		out[id+".yaml"] = []byte(body + "\n")
	}
	return out
}
