package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/strace-me/lotsman/pkg/atomicfile"
	"github.com/strace-me/lotsman/pkg/config"
	"gopkg.in/yaml.v3"
)

// runV2Migrate converts a v1 document into a v2 one ON DISK: configuration.yaml
// plus one file per rule under rules/.
//
// It exists because v2 had a reader and a validator but no producer, which makes
// it untestable end to end — you cannot check a v2 document that nothing can
// write. And the conversion is the interesting part: it is the only place where a
// hand-kept working config has to become the new shape, so its WARNINGS are the
// record of what v1 carried and v2 cannot yet say.
//
// It never overwrites in place. A migration that rewrote the live config would be
// irreversible, and the whole point of the v1 file is that it still works.
func runV2Migrate(args []string) int {
	fs := flag.NewFlagSet("v2-migrate", flag.ExitOnError)
	configPath := fs.String("config", "", "v1 YAML config (required)")
	outDir := fs.String("out", "", "v2 directory to write (required; must not already contain a configuration.yaml)")
	desync := fs.String("desync-strategy", "auto",
		"strategy a v1 `class: zapret` rung maps to: a bundle id, or auto to defer to the knowledge base")
	_ = fs.Parse(args)

	if *configPath == "" || *outDir == "" {
		fmt.Fprintln(os.Stderr, "v2-migrate: -config and -out are required")
		return 2
	}
	// A migration into an existing v2 tree would silently discard hand edits. The
	// warning here is the difference between "this replaced your work" and "this
	// did not run".
	if _, err := os.Stat(filepath.Join(*outDir, "configuration.yaml")); err == nil {
		fmt.Fprintf(os.Stderr, "v2-migrate: %s already has a configuration.yaml; move it aside first\n", *outDir)
		return 1
	}

	data, err := os.ReadFile(*configPath)
	if err != nil {
		fmt.Fprintf(os.Stderr, "v2-migrate: %v\n", err)
		return 1
	}
	doc, err := config.ParseLegacyDocument(data)
	if err != nil {
		fmt.Fprintf(os.Stderr, "v2-migrate: %v\n", err)
		return 1
	}
	migration, err := config.MigrateToV2(doc, func(string) (string, error) { return *desync, nil })
	if err != nil {
		fmt.Fprintf(os.Stderr, "v2-migrate: %v\n", err)
		return 1
	}

	rulesDir := filepath.Join(*outDir, "rules")
	if err := os.MkdirAll(rulesDir, 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "v2-migrate: %v\n", err)
		return 1
	}
	written := 0
	for _, rule := range migration.Rules {
		body, err := yaml.Marshal(rule)
		if err != nil {
			fmt.Fprintf(os.Stderr, "v2-migrate: rule %q: %v\n", rule.ID, err)
			return 1
		}
		path := filepath.Join(rulesDir, rule.ID+".yaml")
		if err := atomicfile.Write(path, body, 0o644); err != nil {
			fmt.Fprintf(os.Stderr, "v2-migrate: %v\n", err)
			return 1
		}
		written++
	}
	header := "# Generated by `lotsmanctl v2-migrate` from " + filepath.Base(*configPath) + ".\n" +
		"# The v1 file is untouched and still authoritative; this is a proposal until you compare\n" +
		"# the two generated sing-box configs byte for byte.\n"
	body, err := yaml.Marshal(migration.Configuration)
	if err != nil {
		fmt.Fprintf(os.Stderr, "v2-migrate: %v\n", err)
		return 1
	}
	if err := atomicfile.Write(filepath.Join(*outDir, "configuration.yaml"), append([]byte(header), body...), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "v2-migrate: %v\n", err)
		return 1
	}

	fmt.Printf("wrote %s/configuration.yaml and %d rule file(s) under %s\n", *outDir, written, rulesDir)
	if len(migration.Warnings) > 0 {
		fmt.Printf("\n%d thing(s) v2 cannot express yet:\n", len(migration.Warnings))
		for _, w := range migration.Warnings {
			fmt.Printf("  - %s\n", w)
		}
	}
	// The advice used to be "generate from both and diff", and that is no longer
	// possible: there is one schema, so the v1 side cannot be generated at all. Printing
	// an instruction that cannot work is worse than printing nothing — the reader either
	// follows it and stops, or learns to distrust the lines under it.
	//
	// What IS available is a preflight, which fetches the lists the document names and
	// checks references and coherence against the REAL bundle store.
	fmt.Printf("\nvalidate the result before starting on it:\n"+
		"  lotsmand -preflight %s\n"+
		"  lotsmand -config %s -dry-run=1\n", *outDir, *outDir)
	return 0
}
